export function getAudioCoverFallback(track: {
  id?: string;
  playlist?: string;
  title?: string;
}): string {
  if (track.playlist === 'Heraldos') return COVER_HERALDOS;
  if (track.playlist === 'Himnario') return COVER_HIMNOS;
  const seed = (track.id || track.title || '').split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const pool = [COVER_ALABANZA, COVER_ADORACION, COVER_ESPERANZA];
  return pool[seed % pool.length];
}

function archiveUrl(identifier: string, filename: string): string {
  return `https://archive.org/download/${identifier}/${encodeURIComponent(filename)}`;
}

